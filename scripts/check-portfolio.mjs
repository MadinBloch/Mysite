import { existsSync, readFileSync } from 'node:fs'
import assert from 'node:assert/strict'
import { CASE_STUDIES } from '../src/data/caseStudies.js'
import { siteStats, statsDisclaimer } from '../src/data/siteStats.js'

const read = path => readFileSync(path,'utf8')
const projects=JSON.parse(read('src/data/projects.json'))
const ids=new Set(projects.map(p=>p.id))
assert.equal(ids.size,projects.length,'Project IDs must be unique')
for(const project of projects) if(project.caseStudySlug) assert.ok(CASE_STUDIES[project.caseStudySlug], 'Case study missing: '+project.caseStudySlug)
assert.ok(CASE_STUDIES['smart-print-operations'])
assert.ok(CASE_STUDIES['email-campaign-engine'])
assert.ok(CASE_STUDIES['kesari-select-backend'])
assert.ok(siteStats.some(x=>x.id==='total-inquiries' && x.a===10000 && x.label.includes('platform')),'Total inquiries not correctly labeled')
assert.ok(siteStats.some(x=>x.id==='daily-inquiries' && x.a===80 && x.b===100),'Approximate daily volume incorrect')
assert.ok(siteStats.some(x=>x.id==='email-import' && x.a===10000),'Email import count missing')
assert.ok(statsDisclaimer.includes('not independent analytics'))
const caseText=read('src/data/caseStudies.js')
assert.ok(caseText.includes('under four seconds') || caseText.includes('four seconds'),'Email import benchmark missing')
assert.ok(caseText.includes('not 10K messages'),'Import and send speed must be differentiated')
const allText=[read('src/components/Hero.jsx'),read('src/components/Experience.jsx'),caseText,read('src/data/projects.json')].join('\n')
assert.ok(!/10K\+\s+(daily|per day|\/day)\s+inquiries/i.test(allText),'Misleading 10K daily inquiries claim')
const resume=readFileSync('public/Madin_Bloch_Resume.pdf')
assert.equal(resume.subarray(0,5).toString(),'%PDF-','Resume must be real PDF')
const pdfText=resume.toString('latin1')
assert.ok(pdfText.includes('Grand Finalist'), 'Hackathon Grand Finalist missing from PDF')
assert.ok(pdfText.includes('10K+') && pdfText.includes('80-100'), 'Inquiries scale missing from PDF')
assert.ok(pdfText.includes('4 seconds'), 'Import benchmark missing from PDF')
assert.ok(existsSync('public/sitemap.xml'))
const html=read('index.html')
assert.ok(html.includes('Backend Developer'))
assert.ok(!html.includes('Senior Laravel Developer'))
console.log('Portfolio content and resume checks passed')
